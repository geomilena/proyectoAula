    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
          String correo = JOptionPane.showInputDialog("Ingrese el CORREO del usuario a eliminar");
        boolean eliminado = false;
        
        for (int i = 0; i < ArrayListUsuarios.listaUsuarios.size(); i++){
            if (ArrayListUsuarios.listaUsuarios.get(i).getCorreo().equals(correo)){
                ArrayListUsuarios.listaUsuarios.remove(i);
                JOptionPane.showMessageDialog(null, "Usuario Eliminado.");
                eliminado = true;
                break;
            }
        }
        
        if (!eliminado){
            JOptionPane.showMessageDialog(null, "Correo no encontrado");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

