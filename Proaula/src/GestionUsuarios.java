    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
         String correo = JOptionPane.showInputDialog("Ingrese el correo del usuario a editar");
        boolean encontrado = false;
        
        for (Usuario u : ArrayListUsuarios.listaUsuarios){
            if (u.getCorreo().equals(correo)){
                String nuevoCorreo = JOptionPane.showInputDialog("Nuevo correo:", u.getCorreo());
                String nuevaContraseña = JOptionPane.showInputDialog("Nueva contraseña");
                u.setCorreo(nuevoCorreo);
                u.setContraseña(nuevaContraseña);
                JOptionPane.showMessageDialog(null, "Usuario actualizado con exito");
                encontrado = true;
                break;
            }
        }
        
        if (!encontrado){
            JOptionPane.showMessageDialog(null, "Correo no encontrado");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

